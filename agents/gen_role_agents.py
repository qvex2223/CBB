"""gen_role_agents — one source per crew role, written out as a Claude Code agent.

Written 2026-11-11 after measuring session a0053cc0 (wildberries, six days, 138 subagent
spawns). Every one of those 138 was `general-purpose`, briefed by hand: median brief 7351
characters. The briefs carried the mechanics well (`bbcurl` 137/138, `CBH_PROJECT` 137,
`scope.md` 136, `poc_runtime` 131) and the judgement badly — the word `victim` appeared in
15 of 138 and `forbidden` in 15 of 138. A hand-written brief carries whatever the
orchestrator remembered at that minute, so the two things it must never drop are the two it
dropped. They belong in the role definition, which is written once and read every spawn.

Source of truth: `agents/roles/<role>.md`. One output per role:
  * `.claude/agents/<role>.md` — `Agent(subagent_type="<role>")` under Claude Code
The body is assembled from placeholders: {{SKILL}} is how this client loads a class skill,
{{SAFETY}} and {{VICTIM}} are the shared blocks that must never drift.

    python3 agents/gen_role_agents.py            # write
    python3 agents/gen_role_agents.py --check    # exit 1 if any output is stale
"""
