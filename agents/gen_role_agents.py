# Shared by every role. Measured on Grok session 01a1ea8b (intigriti/1password, 2026-11-18):
# 1 Caido call in 2964 tool calls (`caido_list_projects`), while workers rebuilt Caido by hand
# — monkeypatched `fetch` inside the page and the extension service worker to see the
# traffic, then fired the target's API from `browser_evaluate` loops with relative paths that
