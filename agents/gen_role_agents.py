#!/usr/bin/env python3
"""gen_role_agents — one source per crew role, written out as a Claude Code agent.

Written 2026-11-11 after measuring session a0053cc0 (wildberries, six days, 138 subagent
spawns). Every one of those 138 was `general-purpose`, briefed by hand: median brief 7351
characters. The briefs carried the mechanics well (`bbcurl` 137/138, `CBH_PROJECT` 137,
`scope.md` 136, `poc_runtime` 131) and the judgement badly — the word `victim` appeared in
15 of 138 and `forbidden` in 15 of 138. A hand-written brief carries whatever the
orchestrator remembered at that minute, so the two things it must never drop are the two it
dropped. They belong in the role definition, which is written once and read every spawn.

Source of truth: `agents/roles/<role>.md`. One output per role:
  * `.claude/agents/<role>.md` — `Agent(subagent_type="<role>")` under Claude Code
The body is assembled from placeholders: {{SKILL}} is how this client loads a class skill,
{{SAFETY}} and {{VICTIM}} are the shared blocks that must never drift.

    python3 agents/gen_role_agents.py            # write
    python3 agents/gen_role_agents.py --check    # exit 1 if any output is stale
"""
from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "agents" / "roles"
OUT = {"claude": REPO / ".claude" / "agents"}

MARK = ("<!-- generated by agents/gen_role_agents.py from agents/roles/{src} — do not edit; "
        "edit the source and re-run -->")

SKILL = {
    "claude": "Load the class skill before the first payload: `Skill(hunt-<class>)`.",
}

NOTE = {
    "claude": ("> You are an in-process `Agent` subagent of the orchestrator. You send requests; the\n"
               "> orchestrator does not (`crew-gate`). Your transcript is open to the operator.\n"),
}

# Shared by every role, byte-identical. The 2026-11-11 measurement: `forbidden` appeared in
# 15 of 138 hand-written briefs, so a worker's knowledge of what it must not do was a coin flip.
SAFETY = """## Rules that hold always — not negotiable, and they outrank the brief
- Every request to a target: `CBH_PROJECT=<platform>/<program> bbcurl …` (scope, pacing,
  mandatory headers, audit log). Never bare `curl` at a target. A gate or classifier refusal is
  final: it is not a target wall, and it is never routed around with another tool or agent.
- The operator's own accounts and data only. Never another user's data, session or identity.
- **Forbidden on every engagement, whatever the brief says:** DoS or load testing · MITM ·
  social engineering · phishing a real human · physical · scanner sweeps (`nuclei`, `dalfox`,
  `sqlmap` outside `bbscan`) · injection-shaped probes outside a loaded `hunt-*` skill (one
  SQL-shaped probe cost this workspace 21 hosts for 21 hours) · anything that moves money,
  stock, queues or availability · any disclosure before a fix.
- The engagement adds its own prohibitions. Read `scope.md`, and grep `blocked-tests/` for the
  route you are about to touch, BEFORE the first request: a previous lane may already have
  closed it as forbidden, and a blocked-test's verdict is at the BOTTOM of the file.
- Anything that could touch another user or availability: stop, write it under `blocked-tests/`
  with the reason, continue elsewhere. Never "just once to see".
- No edits to `scope.md`, `profile.json`, settings, hooks or gates (`control-guard` denies them)."""

# `victim` appeared in 15 of 138 briefs in the same session, and the funnel shows the cost:
# 363 primitives to 28 findings, 134 primitives to 1 finding on wildberries.
VICTIM = """## Impact needs a named victim
Before anything is called a finding, write one sentence naming **who** is harmed — a party that
is not you (another user, a seller, the programme's own operator) — and **what** they lose.
No name? It is a `primitives/` entry, and its own file says which capability is proven and which
impact is not. A client-held random id is a bearer token, not an IDOR. "Could be chained" is not
impact; the chain is impact once a request proves the next link."""


# `cbh report-intel` was named in 103 of session a0053cc0's worker briefs and run zero
# times — it needs a dataset path and an invented query. `cbh precedent` needs neither, so
# the role says exactly which call to make and when.
PRECEDENT = """## Read what the paid hunters did first
`cbh precedent --lead <the file you were given>` — 155 disclosed reports, query derived from
the file, no dataset path. Each hit gives the `FIRST SIGNAL` (what the hunter noticed before
they knew it was a bug), the `mechanic` and the `impact_proof` that was accepted. Run it
BEFORE your first payload, and again when a lane stalls: `cbh precedent --class <class>` for
the class, `cbh precedent --signals <captured body>` to ask which disclosed opening the
response you are holding resembles. A precedent is a hint, never a scope: it does not
authorise anything `scope.md` does not."""


def render(src: Path, client: str) -> str:
    text = src.read_text(encoding="utf-8")
    head, _, body = text.partition("\n---\n")
    body = (body.replace("{{SAFETY}}", SAFETY)
                .replace("{{VICTIM}}", VICTIM)
                .replace("{{PRECEDENT}}", PRECEDENT)
                .replace("{{SKILL}}", SKILL[client]))
    return (head + "\n---\n" + MARK.format(src=src.name) + "\n" + NOTE[client] + body)


def plan() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for src in sorted(SRC.glob("*.md")):
        for client, d in OUT.items():
            out[d / src.name] = render(src, client)
    return out


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    check = "--check" in argv
    stale = []
    for path, text in plan().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        rel = path.relative_to(REPO)
        if current == text:
            continue
        stale.append(str(rel))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {rel}")
    if check:
        for rel in stale:
            print(f"STALE: {rel}")
        if stale:
            print("run: python3 agents/gen_role_agents.py")
            return 1
        print(f"ok — {len(plan())} role file(s) current")
    elif not stale:
        print(f"ok — {len(plan())} role file(s) already current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
