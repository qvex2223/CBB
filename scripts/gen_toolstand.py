def _cell(s: str) -> str:
    """A literal `|` inside a cell ends the column. Escape it."""
    return s.replace("|", "\\|")


def _path(tool: str) -> str:
    w = shutil.which(tool)
    if not w:
        return ""
    home = str(Path.home())
    return w.replace(home, "~")


def render() -> str:
    out = [BEGIN, ""]
    out.append("## Installed — free to use")
    out.append("")
    out.append("| Tool | Path | Use |")
    out.append("|---|---|---|")
    missing_free = []
    for t, (use, _) in FREE.items():
        p = _path(t)
        if not p:
            missing_free.append(t)
            continue
        out.append(f"| `{t}` | `{p}` | {_cell(use)} |")
    if missing_free:
        out.append("")
        out.append("**Declared but NOT on PATH right now — `cbh doctor` should be failing on this:** "
                   + " ".join(f"`{t}`" for t in missing_free))
    out.append("")
    out.append("## Installed, but availability is not permission")
    out.append("")
    out.append("| Tool | Path | The rule |")
    out.append("|---|---|---|")
    for t, rule in RESTRICTED.items():
        p = _path(t)
        out.append(f"| `{t}` | `{p or '**NOT ON PATH**'}` | {_cell(rule)} |")
    out.append("")
    out.append("## Not installed — use the substitute, do not write the command")
    out.append("")
    out.append("| Missing | Why | Instead |")
    out.append("|---|---|---|")
    appeared = []
    for t, (why, instead) in ABSENT.items():
        if _path(t):
            appeared.append(t)
            continue
        out.append(f"| `{t}` | {_cell(why)} | {_cell(instead)} |")
    if appeared:
        out.append("")
        out.append("**Listed here but now PRESENT — re-run `--write`, and use them:** "
                   + " ".join(f"`{t}`" for t in appeared))
    out.append("")
    out.append("## Reference data — local, no request cost")
    out.append("")
    out.append("`~/security-research/tools/data/`: `keyhacks.md` (validate a leaked key per "
               "provider — the lead -> demonstrated-impact step), `takeover-fingerprints.json` "
               "(`can-i-take-over-xyz`), `bt-hackerone.json` / `bt-bugcrowd.json` / "
               "`bt-intigriti.json` (`bounty-targets-data` scope dumps — a platform-published "
               "second source to check a scope claim against).")
    out.append("")
    out.append("> This block is generated. Re-run `python3 scripts/gen_toolstand.py --write` "
               "after installing or losing a tool; `cbh doctor` checks PATH against "
               "`engine/workspace_check.py::TOOLS_REQUIRED`, and "
               "`tests/test_tool_stand.py` fails the build if this block calls an installed "
               "tool missing.")
    out.append("")
    out.append(END)
    return "\n".join(out)


def current_block(text: str) -> str | None:
    if BEGIN not in text or END not in text:
        return None
    return text[text.index(BEGIN):text.index(END) + len(END)]


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    block = render()
    text = SKILL.read_text(encoding="utf-8")
    cur = current_block(text)
    if a.write:
        if cur is None:
            print(f"ERROR: markers not present in {SKILL}; insert "
                  f"{BEGIN} / {END} around the tool tables first", file=sys.stderr)
            return 1
        SKILL.write_text(text.replace(cur, block), encoding="utf-8")
        print(f"wrote {SKILL.relative_to(REPO)}")
        return 0
    if a.check:
        if cur is None:
            print("STALE  markers missing")
            return 1
        if cur != block:
            print("STALE  bb-local-toolkit tool tables disagree with PATH — "
                  "python3 scripts/gen_toolstand.py --write")
            return 1
        print("OK     bb-local-toolkit matches PATH")
        return 0
    print(block)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
