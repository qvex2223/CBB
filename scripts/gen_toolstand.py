"""gen_toolstand — render the local tool tables in bb-local-toolkit from live PATH.

Why this is generated and not written by hand: on 2026-10-21 the hand-written table in
`skills/bb-local-toolkit/SKILL.md` was worse than missing. It carried paths that had
moved (`/usr/bin/subfinder`, `/usr/local/bin/httpx` — both actually under
`~/.local/bin/`) and it listed `gf`, `assetfinder`, `gitleaks` and `subzy` under
**"Not installed — use the substitute, do not write the command"** while all four were on
PATH. A stale "installed" row costs one `command not found`; a stale "not installed" row
is a standing instruction to the agent not to use a tool it has.

So: one generator, one marker block, and a `--check` mode a test calls.

    python3 scripts/gen_toolstand.py            # print the rendered block
    python3 scripts/gen_toolstand.py --write    # rewrite the block in the skill
    python3 scripts/gen_toolstand.py --check    # exit 1 if the skill is stale
"""
